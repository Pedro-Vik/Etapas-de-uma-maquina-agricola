-- Consultas de gestão — Oracle
-- Executar após criar as tabelas e carregar os dados correspondentes.

-- SQL 1 / Q01: total de registros na base de culturas.
SELECT COUNT(*) AS TOTAL_REGISTROS
FROM CULTURAS_AGRICOLAS;

-- SQL 2 / Q02: quantidade de amostras por cultura.
SELECT CULTURA, COUNT(*) AS QUANTIDADE_AMOSTRAS
FROM CULTURAS_AGRICOLAS
GROUP BY CULTURA
ORDER BY QUANTIDADE_AMOSTRAS DESC, CULTURA;

-- SQL 3 / Q03: médias das condições por cultura.
SELECT
    CULTURA,
    ROUND(AVG(N), 2) AS MEDIA_N,
    ROUND(AVG(P), 2) AS MEDIA_P,
    ROUND(AVG(K), 2) AS MEDIA_K,
    ROUND(AVG(TEMPERATURA), 2) AS MEDIA_TEMPERATURA,
    ROUND(AVG(UMIDADE), 2) AS MEDIA_UMIDADE,
    ROUND(AVG(PH), 2) AS MEDIA_PH,
    ROUND(AVG(PRECIPITACAO), 2) AS MEDIA_PRECIPITACAO
FROM CULTURAS_AGRICOLAS
GROUP BY CULTURA
ORDER BY CULTURA;

-- SQL 4 / Q04: limites observados de cada variável.
SELECT 'N' AS VARIAVEL, MIN(N) AS VALOR_MINIMO, MAX(N) AS VALOR_MAXIMO FROM CULTURAS_AGRICOLAS
UNION ALL
SELECT 'P', MIN(P), MAX(P) FROM CULTURAS_AGRICOLAS
UNION ALL
SELECT 'K', MIN(K), MAX(K) FROM CULTURAS_AGRICOLAS
UNION ALL
SELECT 'TEMPERATURA', MIN(TEMPERATURA), MAX(TEMPERATURA) FROM CULTURAS_AGRICOLAS
UNION ALL
SELECT 'UMIDADE', MIN(UMIDADE), MAX(UMIDADE) FROM CULTURAS_AGRICOLAS
UNION ALL
SELECT 'PH', MIN(PH), MAX(PH) FROM CULTURAS_AGRICOLAS
UNION ALL
SELECT 'PRECIPITACAO', MIN(PRECIPITACAO), MAX(PRECIPITACAO) FROM CULTURAS_AGRICOLAS;

-- SQL 5 / Q05: cultura com maior média de precipitação registrada.
SELECT CULTURA, MEDIA_PRECIPITACAO
FROM (
    SELECT CULTURA, AVG(PRECIPITACAO) AS MEDIA_PRECIPITACAO
    FROM CULTURAS_AGRICOLAS
    GROUP BY CULTURA
    ORDER BY AVG(PRECIPITACAO) DESC
)
FETCH FIRST 1 ROW ONLY;

-- SQL 6 / Q06: correlações lineares. Correlação não implica causalidade.
SELECT
    CORR(N, P) AS CORR_N_P,
    CORR(N, K) AS CORR_N_K,
    CORR(TEMPERATURA, UMIDADE) AS CORR_TEMP_UMIDADE,
    CORR(PH, PRECIPITACAO) AS CORR_PH_PRECIP
FROM CULTURAS_AGRICOLAS;

-- SQL 7 / Q07: leituras de sensores por dia (requer histórico das Fases 1 e 2).
SELECT
    TRUNC(DATA_LEITURA) AS DIA,
    COUNT(*) AS QUANTIDADE_LEITURAS,
    ROUND(AVG(UMIDADE_SOLO), 2) AS MEDIA_UMIDADE_SOLO,
    ROUND(AVG(PH_SOLO), 2) AS MEDIA_PH
FROM LEITURAS_SENSORES
GROUP BY TRUNC(DATA_LEITURA)
ORDER BY DIA;

-- SQL 8 / Q08: distribuição por estado da bomba (requer campo real correspondente).
SELECT NVL(BOMBA_ATIVA, 'NI') AS ESTADO_BOMBA,
       COUNT(*) AS QUANTIDADE_LEITURAS
FROM LEITURAS_SENSORES
GROUP BY BOMBA_ATIVA
ORDER BY ESTADO_BOMBA;

-- Conferência da carga mais recente.
SELECT COUNT(*) AS TOTAL_REGISTROS,
       MIN(DATA_IMPORTACAO) AS PRIMEIRA_IMPORTACAO,
       MAX(DATA_IMPORTACAO) AS ULTIMA_IMPORTACAO
FROM CULTURAS_AGRICOLAS;
