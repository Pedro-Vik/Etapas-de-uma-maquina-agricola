CREATE TABLE CULTURAS_AGRICOLAS (
    ID_REGISTRO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    N                 NUMBER(10, 3),
    P                 NUMBER(10, 3),
    K                 NUMBER(10, 3),
    TEMPERATURA       NUMBER(10, 4),
    UMIDADE           NUMBER(10, 4),
    PH                NUMBER(6, 3),
    PRECIPITACAO      NUMBER(12, 4),
    CULTURA           VARCHAR2(100 CHAR) NOT NULL,
    DATA_IMPORTACAO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CULTURAS_AGRICOLAS PRIMARY KEY (ID_REGISTRO)
);

CREATE INDEX IX_CULTURAS_LABEL ON CULTURAS_AGRICOLAS (CULTURA);

-- Modelo para leituras do protótipo. Confirmar unidades e campos antes da carga.
CREATE TABLE LEITURAS_SENSORES (
    ID_LEITURA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DATA_LEITURA      TIMESTAMP NOT NULL,
    UMIDADE_SOLO      NUMBER(10, 4),
    PH_SOLO           NUMBER(6, 3),
    NITROGENIO        NUMBER(10, 3),
    FOSFORO           NUMBER(10, 3),
    POTASSIO          NUMBER(10, 3),
    BOMBA_ATIVA       CHAR(1),
    ORIGEM_DADO       VARCHAR2(100 CHAR),
    DATA_IMPORTACAO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LEITURAS_SENSORES PRIMARY KEY (ID_LEITURA),
    CONSTRAINT CK_LEITURAS_BOMBA CHECK (BOMBA_ATIVA IN ('S', 'N') OR BOMBA_ATIVA IS NULL)
);

CREATE INDEX IX_LEITURAS_DATA ON LEITURAS_SENSORES (DATA_LEITURA);

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN ('CULTURAS_AGRICOLAS', 'LEITURAS_SENSORES')
ORDER BY TABLE_NAME;
